"""Pin map tables, generated from the board's functional pin map (the X-macro tables in the hf-pincfg header).

Regions: ``pins-summary``, ``pins-esp32``, ``pins-adc``.
"""

from __future__ import annotations

import hal_extract as hx

#: Pin sources with a table. On Flux V1 every functional pin is an ESP32-S3 GPIO (the MAX22200 and TLE92466ED
#: chip types exist in the header but have no rows).
CHIPS = {
    "ESP32_INTERNAL": ("ESP32-S3 GPIO", "pins-esp32"),
}


def _src(page) -> str:
    rel = hx.BOARD["pin_header"]
    return f"Generated by `tools/docs/gen.py` from\n[`{rel.rsplit('/', 1)[-1]}`]({page.rel(rel)});\ndo not edit."


def _pin(p: dict) -> str:
    if p["chip"] == "ESP32_INTERNAL":
        return f"GPIO{p['pin']}"
    return f"GPIO{p['pin']}"


def _gpio_table(page, chip: str) -> str:
    rows = [p for p in hx.pins()["gpio"] if p["chip"] == chip]
    out = [
        _src(page),
        "",
        "| Function | Pin | Category | Name (for `GpioManager`) | Active | Pull | Max mA |",
        "| --- | --- | --- | --- | --- | --- | ---: |",
    ]
    for p in sorted(rows, key=lambda r: (r["unit"], r["bank"], r["pin"])):  # in GPIO order
        out.append(
            f"| `{p['id']}` | {_pin(p)} | {p['category'].title()} | `{p['name']}` | "
            f"{'low' if p['active_low'] else 'high'} | {p['pull']} | {p['max_ma'] or '-'} |"
        )
    return "\n".join(out)


def summary(page) -> str:
    data = hx.pins()
    out = [_src(page), "", "| Pin source | Functional pins | Of which: core | comm | GPIO |", "| --- | ---: | ---: | ---: | ---: |"]
    for chip, (label, _region) in CHIPS.items():
        rows = [p for p in data["gpio"] if p["chip"] == chip]
        if not rows:
            continue
        cats = [p["category"] for p in rows]
        out.append(f"| {label} | {len(rows)} | {cats.count('CORE')} | {cats.count('COMM')} | {cats.count('GPIO')} |")
    out.append(f"| ADC channels | {len(data['adc'])} | | | |")
    return "\n".join(out)


def adc(page) -> str:
    out = [_src(page), "", "| Channel | Name (for `AdcManager`) | Source | Ch | Bits | Full scale | Description |",
           "| --- | --- | --- | ---: | ---: | ---: | --- |"]
    for a in hx.pins()["adc"]:
        chip = {"ESP32_INTERNAL": "ESP32-S3 ADC1", "ADS7952_EXTERNAL": f"ADS7952 #{a['unit']}"}.get(a["chip"], a["chip"])
        div = "" if a["divider"] == 1.0 else f" (divider {a['divider']:g})"
        out.append(f"| `{a['id']}` | `{a['name']}` | {chip} | {a['channel']} | {a['bits']} | {a['max_mv']} mV{div} | "
                   f"{a['description']} |")
    return "\n".join(out)


REGIONS = {
    "pins-summary": summary,
    "pins-adc": adc,
    **{region: (lambda page, c=chip: _gpio_table(page, c)) for chip, (_l, region) in CHIPS.items()},
}
